"""Learning: outcomes -> bucket statistics -> memory.md.

buckets.json is recomputed from the whole outcomes.jsonl every run, so it is
idempotent. A success is a candidate that passed every gate; each shipped hill
with at least one climb in engagement.csv adds one more success to its bucket.
Only candidates that reached the data stage count (license/metadata skips are
recorded but do not move a bucket). Lessons are generated by rule from counts.
"""

from __future__ import annotations

import csv
import json
from collections import Counter, defaultdict
from pathlib import Path

from .gates import GATES
from .select import bucket_rate

GATE_LABEL = {
    "valid": "Valid", "baseline_scores": "Baseline scores", "deterministic": "Deterministic",
    "fast": "Fast", "headroom": "Headroom", "not_trivial": "Not trivial", "no_leak": "No leak",
    "rejects_junk": "Rejects junk", "prepare": "data preparation",
}
COUNTED_STAGES = {"prepare", "gates"}


def read_jsonl(path: Path) -> list[dict]:
    if not Path(path).exists():
        return []
    return [json.loads(l) for l in Path(path).read_text().splitlines() if l.strip()]


def append_jsonl(path: Path, records: list[dict]) -> None:
    with open(path, "a") as fh:
        for r in records:
            fh.write(json.dumps(r, default=str) + "\n")


def read_engagement(path: Path) -> list[dict]:
    if not Path(path).exists():
        return []
    with open(path) as fh:
        return [r for r in csv.DictReader(fh) if r.get("hill")]


def ensure_engagement(path: Path) -> None:
    if not Path(path).exists():
        Path(path).write_text("hill,climbs,stars,date\n")


def compute_buckets(outcomes: list[dict], engagement: list[dict]) -> dict:
    stats: dict[str, dict] = defaultdict(lambda: {"successes": 0, "failures": 0, "engagement_bonus": 0})
    hill_bucket = {}
    for o in outcomes:
        if o.get("stage") not in COUNTED_STAGES:
            continue
        b = o["bucket"]
        if o.get("shipped"):
            stats[b]["successes"] += 1
            hill_bucket[o.get("hill")] = b
        else:
            stats[b]["failures"] += 1
    climbed = set()
    for row in engagement:
        try:
            if int(float(row.get("climbs") or 0)) >= 1:
                climbed.add(row["hill"])
        except ValueError:
            continue
    for hill in climbed:
        if hill in hill_bucket:
            stats[hill_bucket[hill]]["engagement_bonus"] += 1
    out = {}
    for b, st in sorted(stats.items()):
        out[b] = {**st, "rate": round(bucket_rate(st), 4)}
    return out


def _dims(bucket: str) -> dict[str, str]:
    source, task, size, feat = bucket.split("|")
    return {"source": source, "task": task, "size": size, "feat": feat}


DIM_PHRASE = {
    "source": lambda v: f"{'OpenML' if v == 'openml' else v.capitalize()} candidates",
    "task": lambda v: f"{v} datasets",
    "size": lambda v: {"small": "datasets under 10k rows", "medium": "datasets of 10k-50k rows",
                       "large": "datasets over 50k rows"}[v],
    "feat": lambda v: {"f<20": "datasets with under 20 features", "f20-60": "datasets with 20-60 features",
                       "f>60": "datasets with over 60 features"}[v],
}


def lessons(outcomes: list[dict], limit: int = 10) -> list[str]:
    counted = [o for o in outcomes if o.get("stage") in COUNTED_STAGES]
    found: list[tuple[int, str]] = []
    # Failure concentrations: dimension value x first failing gate.
    by_dim_gate: Counter = Counter()
    by_dim: Counter = Counter()
    by_dim_ship: Counter = Counter()
    for o in counted:
        for dim, val in _dims(o["bucket"]).items():
            by_dim[(dim, val)] += 1
            if o.get("shipped"):
                by_dim_ship[(dim, val)] += 1
            elif o.get("first_failed_gate"):
                by_dim_gate[(dim, val, o["first_failed_gate"])] += 1
    for (dim, val, gate), n in by_dim_gate.items():
        total = by_dim[(dim, val)]
        if n >= 2 and n / total >= 0.5:
            where = "at data preparation" if gate == "prepare" else f"the {GATE_LABEL.get(gate, gate)} gate"
            found.append((n * 10 + total, f"{DIM_PHRASE[dim](val)} failed {where} {n} of {total} times"))
    for (dim, val), n in by_dim_ship.items():
        total = by_dim[(dim, val)]
        if n >= 2 and n / total >= 0.6:
            found.append((n * 10 + total - 1, f"{DIM_PHRASE[dim](val)} shipped {n} of {total} attempts"))
    # Pre-build skips, by reason.
    skip_reasons = Counter(o.get("failure_reason", "").split(":")[0].split("'")[0].strip()
                           for o in outcomes if o.get("stage") == "enrich")
    for reason, n in skip_reasons.items():
        if n >= 2 and reason:
            found.append((n * 5, f"{n} candidates were skipped before download: {reason}"))
    found.sort(key=lambda t: t[0], reverse=True)
    out, seen_text = [], set()
    for _, text in found:
        if text not in seen_text:
            seen_text.add(text)
            out.append(text)
    return out[:limit]


def write_memory(path: Path, buckets: dict, outcomes: list[dict], run_id: str) -> str:
    lines = [f"# Hill Scout memory", "", f"_Rewritten after run {run_id}. Read at the start of every run._", "",
             "## Bucket success rates", "", "| bucket | shipped | failed | climb bonus | rate |", "|---|---|---|---|---|"]
    for b, st in sorted(buckets.items(), key=lambda kv: -kv[1]["rate"]):
        lines.append(f"| {b} | {st['successes']} | {st['failures']} | {st['engagement_bonus']} | {st['rate']:.2f} |")
    lines += ["", "## Lessons", ""]
    ls = lessons(outcomes)
    lines += [f"- {l}" for l in ls] or ["- not enough attempts yet to draw a lesson"]
    text = "\n".join(lines) + "\n"
    Path(path).write_text(text)
    return text
